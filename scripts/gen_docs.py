def _subparsers_action(parser: argparse.ArgumentParser) -> argparse._SubParsersAction:
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            return action
    raise GenerationError("build_parser() has no subcommands")


def _find_option(parser: argparse.ArgumentParser, flag: str) -> argparse.Action:
    for action in parser._actions:  # noqa: SLF001
        if flag in action.option_strings:
            return action
    raise GenerationError(f"build_parser() has no {flag!r} option")


def _subcommand_help(sub_action: Any, name: str) -> str:
    for choice_action in sub_action._choices_actions:  # noqa: SLF001
        if choice_action.dest == name:
            return choice_action.help or ""
    return ""


def _render_flag_default(action: argparse.Action) -> str:
    if action.nargs == 0:  # store_true / store_false
        return f"`{str(bool(action.default)).lower()}`"
    if action.default is None:
        return "*unset*"
    return f"`{action.default}`"


def _render_flag_help(action: argparse.Action) -> str:
    help_text = action.help or ""
    if action.choices:
        help_text = f"{help_text} One of: {', '.join(str(c) for c in action.choices)}.".strip()
    return help_text


def _render_flags_table(actions: list[argparse.Action]) -> list[str]:
    out = ["| Flag | Default | Description |", "| --- | --- | --- |"]
    for action in actions:
        flags = ", ".join(f"`{f}`" for f in action.option_strings)
        default = cell(_render_flag_default(action))
        help_text = cell(_render_flag_help(action))
        out.append(f"| {flags} | {default} | {help_text} |")
    return out


def render_cli() -> str:
    parser = build_parser()
    out: list[str] = [
        f"<!-- {BANNER} -->",
        "",
        "# CLI reference",
        "",
        f"> {BANNER}",
        "> Edit the `help=` text and arguments in `src/maverick/cli.py`, or the prose in",
        "> `docs/reference/_cli.intro.md`, then run `python scripts/gen_docs.py`.",
        "",
        read_include("_cli.intro.md"),
        "",
        "## Global options",
        "",
        "Given before the subcommand: `maverick -c config.yaml render kitchen`.",
        "",
    ]
    global_actions = [
        _find_option(parser, "--config"),
        _find_option(parser, "--log-level"),
        _find_option(parser, "--verbose"),
    ]
    out.extend(_render_flags_table(global_actions))
    out.append("")

    out.append("## Subcommands")
    out.append("")
    sub_action = _subparsers_action(parser)
    for name, subparser in sub_action.choices.items():
        out.append(f"### `maverick {name}`")
        out.append("")
        help_text = _subcommand_help(sub_action, name)
        if help_text:
            out.append(help_text)
            out.append("")
        positionals = [
            a for a in subparser._actions if not a.option_strings  # noqa: SLF001
        ]
        optionals = [
            a
            for a in subparser._actions  # noqa: SLF001
            if a.option_strings and "-h" not in a.option_strings
        ]
        if positionals:
            out.append("| Argument | Description |")
            out.append("| --- | --- |")
            for action in positionals:
                suffix = " (optional)" if action.nargs == "?" else ""
                out.append(f"| `{action.dest}`{suffix} | {cell(action.help or '')} |")
            out.append("")
        if optionals:
            out.extend(_render_flags_table(optionals))
            out.append("")

    out.append("## Environment variables")
    out.append("")
    out.append("| Variable | Description |")
    out.append("| --- | --- |")
    for name, description in ENVIRONMENT_VARIABLES:
        out.append(f"| `{name}` | {cell(description)} |")
    out.append("")

    out.append("## Exit codes")
    out.append("")
    out.append("| Code | Meaning |")
    out.append("| --- | --- |")
    for code, meaning in EXIT_CODES:
        out.append(f"| `{code}` | {cell(meaning)} |")
    out.append("")

    return "\n".join(out).rstrip() + "\n"


