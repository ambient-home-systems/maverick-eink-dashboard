def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write anything; exit 1 if a page is out of date",
    )
    args = parser.parse_args(argv)

    try:
        rendered = {name: render() for name, render in PAGES.items()}
    except GenerationError as exc:
        print(f"gen_docs: {exc}", file=sys.stderr)
        return 1

    stale: list[str] = []
    for name, content in rendered.items():
        path = DOCS / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != content:
                stale.append(str(path.relative_to(ROOT)))
            continue
        if current == content:
            print(f"unchanged {path.relative_to(ROOT)}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote     {path.relative_to(ROOT)}")

    if stale:
        print(
            "gen_docs: out of date: "
            + ", ".join(stale)
            + "\nRun `python scripts/gen_docs.py` and commit the result.",
            file=sys.stderr,
        )
        return 1
    if args.check:
        print("gen_docs: reference pages are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
