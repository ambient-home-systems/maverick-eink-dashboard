#!/usr/bin/env python3
"""Generate the reference documentation from the code.

The reference pages under ``docs/reference/`` are derived from the models, the
enums and the transport registry, so they cannot drift from what the software
does. Nothing here is hand-maintained prose about a config key: the key's own
``Field(description=...)`` in :mod:`maverick.config` is the single copy, and
this script arranges it.

Three rules keep that true, and each one fails the build rather than emitting
something stale:

* every field of every model reachable from :class:`~maverick.config.Config`
  must carry a description;
* every model reachable from ``Config`` must be claimed by a section below;
* every ``self.option("x")`` a transport reads must appear in that transport's
  ``options_doc``.

Hand-written prose lives in ``docs/reference/_*.md`` and is included verbatim,
so the generated page can say things the models cannot.

Usage::

    python scripts/gen_docs.py            # write the pages
    python scripts/gen_docs.py --check    # exit 1 if the pages are out of date
"""

